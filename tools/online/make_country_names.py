#!/usr/bin/env python3
"""Writes app/src/online/country_names.inc: each country's name in Spanish, English and Portuguese (the game's
languages), for the Linux build, where no system call gives a country's name in the player's language (Windows has
GetGeoInfoEx: online/flags.cpp Name).

mk9-lauta (2026-11-13). The names are the Unicode CLDR's (cldr-json, territories.json of es, en and pt: the Unicode
License, app/thirdparty/country_data/CLDR-LICENSE). Only the codes the flags atlas has (flags_codes.inc).

Usage: python tools/online/make_country_names.py
"""
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
URL = ('https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/'
       '{lang}/territories.json')
LICENSE_URL = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/LICENSE'


def territories(lang):
    data = json.loads(urllib.request.urlopen(URL.format(lang=lang), timeout=60).read().decode('utf-8'))
    return data['main'][lang]['localeDisplayNames']['territories']


def main():
    codes_text = open(os.path.join(ROOT, 'app', 'src', 'online', 'flags_codes.inc'), encoding='utf-8').read()
    codes = [c.upper() for c in re.findall(r'"([a-z]{2})"', codes_text)]
    names = {lang: territories(lang) for lang in ('es', 'en', 'pt')}
    lines = ['// Generated by tools/online/make_country_names.py from the Unicode CLDR (cldr-json: territories of es, '
             'en, pt;',
             '// app/thirdparty/country_data/CLDR-LICENSE): code, Spanish, English, Portuguese name, by code.']
    missing = []
    for code in sorted(set(codes)):
        row = [names[lang].get(code, '') for lang in ('es', 'en', 'pt')]
        if not all(row):
            missing.append(code)
            row = [r or code for r in row]
        esc = [r.replace('\\', '\\\\').replace('"', '\\"') for r in row]
        lines.append('{"%s", "%s", "%s", "%s"},' % (code, esc[0], esc[1], esc[2]))
    out = os.path.join(ROOT, 'app', 'src', 'online', 'country_names.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    lic_dir = os.path.join(ROOT, 'app', 'thirdparty', 'country_data')
    os.makedirs(lic_dir, exist_ok=True)
    lic = urllib.request.urlopen(LICENSE_URL, timeout=60).read().decode('utf-8')
    with open(os.path.join(lic_dir, 'CLDR-LICENSE'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(lic)
    print(f'{len(lines) - 2} countries -> {out}' + (f' (no name for {missing})' if missing else ''))


if __name__ == '__main__':
    sys.exit(main())
