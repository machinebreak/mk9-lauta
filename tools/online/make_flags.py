#!/usr/bin/env python3
"""Builds the online screens' flag atlas (app/src/online/flags_atlas.png + flags_codes.inc, online/flags.cpp).

    python tools/online/make_flags.py

Downloads every country's flag (two-letter ISO 3166 codes) from flagcdn.com (Flagpedia's flags, in the public domain),
40 pixels wide, fits each one into a 40x30 cell (aspect kept, centred, the rest transparent) and writes the cells in
16 columns, in the order of flags_codes.inc ("ar", "br", ...). Run again only to change the set or the size.
"""
import io
import json
import os
import urllib.request

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'app', 'src', 'online')
CELL_W, CELL_H, COLUMNS = 40, 30, 16


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'mk9-lauta-build'}), timeout=30) as r:
        return r.read()


def main():
    names = json.loads(get('https://flagcdn.com/en/codes.json'))
    codes = sorted(c for c in names if len(c) == 2)
    rows = (len(codes) + COLUMNS - 1) // COLUMNS
    atlas = Image.new('RGBA', (COLUMNS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    for i, code in enumerate(codes):
        flag = Image.open(io.BytesIO(get(f'https://flagcdn.com/w80/{code}.png'))).convert('RGBA')
        scale = min(CELL_W / flag.width, CELL_H / flag.height)
        w, h = max(1, round(flag.width * scale)), max(1, round(flag.height * scale))
        flag = flag.resize((w, h), Image.LANCZOS)
        x = (i % COLUMNS) * CELL_W + (CELL_W - w) // 2
        y = (i // COLUMNS) * CELL_H + (CELL_H - h) // 2
        atlas.paste(flag, (x, y), flag)
    atlas.save(os.path.join(OUT, 'flags_atlas.png'), optimize=True)
    with open(os.path.join(OUT, 'flags_codes.inc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/online/make_flags.py: the flags of flags_atlas.png, in cell order.\n')
        for i in range(0, len(codes), 16):
            f.write(' '.join(f'"{c}",' for c in codes[i:i + 16]) + '\n')
    print(f'{len(codes)} flags, {atlas.width}x{atlas.height}')


if __name__ == '__main__':
    main()
