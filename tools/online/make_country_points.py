#!/usr/bin/env python3
"""Builds the countries' centre points (app/src/online/country_points.inc, flags.cpp's round trip estimate) from
Google's DSPL canonical countries (BSD 3-clause: app/thirdparty/country_data/LICENSE).

    python tools/online/make_country_points.py
"""
import csv
import io
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
URL = 'https://raw.githubusercontent.com/google/dspl/master/samples/google/canonical/countries.csv'


def main():
    text = urllib.request.urlopen(URL, timeout=30).read().decode('utf-8')
    rows = [r for r in csv.DictReader(io.StringIO(text)) if r['latitude'] and r['longitude']]
    rows.sort(key=lambda r: r['country'])
    out = os.path.join(ROOT, 'app', 'src', 'online', 'country_points.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/online/make_country_points.py from Google\'s DSPL canonical countries\n')
        f.write('// (app/thirdparty/country_data/LICENSE): code, latitude, longitude, by code.\n')
        for r in rows:
            f.write(f'{{"{r["country"]}", {float(r["latitude"]):.4f}f, {float(r["longitude"]):.4f}f}},\n')
    print(f'{len(rows)} countries -> {out}')


if __name__ == '__main__':
    main()
